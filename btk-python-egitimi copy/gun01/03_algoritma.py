"""Algoritma: toplamdan ortalamaya. Sentetik eğitim örneği; doğrudan çalıştırılabilir."""
# Girdi: üç işlem süresi. İşlem: topla, sayıya böl. Çıktı: ortalama.
sure_1, sure_2, sure_3 = 2, 4, 9
kayit_sayisi = 3
toplam = sure_1 + sure_2 + sure_3
ortalama = toplam / kayit_sayisi
print(f"Toplam: {toplam} gün")
print(f"Ortalama: {ortalama:.2f} gün")
# Önce kağıtta 2 + 4 + 9 hesabını yapın; kodun çıktısını doğrulayın.
